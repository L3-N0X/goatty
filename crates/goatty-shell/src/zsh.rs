//! The managed ZDOTDIR: goatty's zsh startup files.
//!
//! The startup files themselves are static (`zsh/*.zsh` in this crate, so
//! they can be read and syntax-checked as they are). Everything that
//! depends on settings or paths goes into one generated `settings.zsh`,
//! which `.zshenv` sources first. See `docs/managed-zsh.md` for the startup
//! sequence.

use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use goatty_config::ZshSettings;

use crate::dirs::Dirs;
use crate::tools::{self, Kind};

pub const ZSHENV: &str = include_str!("../zsh/zshenv.zsh");
pub const ZPROFILE: &str = include_str!("../zsh/zprofile.zsh");
pub const ZSHRC: &str = include_str!("../zsh/zshrc.zsh");
pub const INTEGRATION: &str = include_str!("../zsh/integration.zsh");
pub const STARSHIP_TOML: &str = include_str!("../zsh/starship.toml");

/// Inputs for [`render`].
pub struct ZshConfig<'a> {
    pub settings: &'a ZshSettings,
    pub dirs: &'a Dirs,
    /// The goattyd binary `goatty-setup` runs. `None`: `goattyd` from PATH.
    pub daemon_exe: Option<&'a Path>,
}

/// A file of the managed ZDOTDIR.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedFile {
    pub name: &'static str,
    pub contents: String,
}

/// Every file of the managed ZDOTDIR.
pub fn render(cfg: &ZshConfig<'_>) -> Vec<GeneratedFile> {
    let file = |name, contents: &str| GeneratedFile { name, contents: contents.to_owned() };
    vec![
        GeneratedFile { name: "settings.zsh", contents: render_settings(cfg) },
        file(".zshenv", ZSHENV),
        file(".zprofile", ZPROFILE),
        file(".zshrc", ZSHRC),
        file("integration.zsh", INTEGRATION),
        file("starship.toml", STARSHIP_TOML),
    ]
}

/// Feature names as the `.zshrc` knows them, for the enabled ones.
pub fn enabled_features(s: &ZshSettings) -> Vec<&'static str> {
    [
        ("autosuggestions", s.autosuggestions),
        ("syntax-highlighting", s.syntax_highlighting),
        ("starship", s.starship),
        ("atuin", s.atuin),
        ("fzf", s.fzf),
        ("integration", s.integration),
    ]
    .into_iter()
    .filter_map(|(name, on)| on.then_some(name))
    .collect()
}

fn render_settings(cfg: &ZshConfig<'_>) -> String {
    let d = cfg.dirs;
    let s = cfg.settings;
    let mut out = String::from(
        "# goatty managed zsh: settings and paths, read first by .zshenv.\n\
         # Generated by goatty from its settings and rewritten whenever a session starts: don't edit.\n",
    );
    let mut scalar = |name: &str, value: &str| out.push_str(&format!("typeset -g {name}={}\n", quote(value)));
    scalar("_goatty_dir", &d.zsh_dir().to_string_lossy());
    scalar("_goatty_bin", &d.bin_dir().to_string_lossy());
    scalar("_goatty_cache", &d.cache.to_string_lossy());
    scalar("_goatty_user_zshrc", &d.user_zshrc().to_string_lossy());
    scalar("_goatty_hint_marker", &d.hint_marker().to_string_lossy());
    scalar("_goatty_daemon", &cfg.daemon_exe.map(|p| p.to_string_lossy().into_owned()).unwrap_or_default());
    scalar("_goatty_user_env", if s.user_env { "1" } else { "0" });
    scalar("_goatty_user_rc", if s.user_rc { "1" } else { "0" });
    out.push_str(&format!("typeset -ga _goatty_features=({})\n", enabled_features(s).join(" ")));
    for t in tools::TOOLS {
        if let Kind::ZshPlugin { .. } = t.kind {
            let paths: Vec<String> = t.plugin_candidates(d).iter().map(|p| quote(&p.to_string_lossy())).collect();
            out.push_str(&format!("typeset -ga _goatty_paths_{}=(\n  {}\n)\n", t.id.replace('-', "_"), paths.join("\n  ")));
        }
    }
    out
}

/// Quote for zsh: single quotes, with `'` as `'\''`.
pub fn quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// Write `files` into `dir`, replacing only files whose contents changed.
/// Each file is replaced atomically (temp file, then rename), so a shell
/// starting at the same moment never reads a half-written file. Returns
/// whether anything changed. Also creates the cache dir the `.zshrc` uses.
pub fn write(dirs: &Dirs, files: &[GeneratedFile]) -> Result<bool> {
    let dir = dirs.zsh_dir();
    std::fs::create_dir_all(&dir).with_context(|| format!("create {}", dir.display()))?;
    let _ = std::fs::create_dir_all(&dirs.cache);
    let mut changed = false;
    for f in files {
        let path = dir.join(f.name);
        if std::fs::read(&path).is_ok_and(|old| old == f.contents.as_bytes()) {
            continue;
        }
        let tmp: PathBuf = dir.join(format!(".{}.tmp-{}", f.name.trim_start_matches('.'), std::process::id()));
        std::fs::write(&tmp, &f.contents).with_context(|| format!("write {}", tmp.display()))?;
        std::fs::rename(&tmp, &path).with_context(|| format!("replace {}", path.display()))?;
        changed = true;
    }
    Ok(changed)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quoting() {
        assert_eq!(quote("/a b/c"), "'/a b/c'");
        assert_eq!(quote("it's"), r"'it'\''s'");
        assert_eq!(quote(""), "''");
    }

    #[test]
    fn settings_reflect_toggles() {
        let dirs = Dirs::under(Path::new("/r o/ot's"));
        let s = ZshSettings { starship: false, user_rc: true, ..Default::default() };
        let out = render_settings(&ZshConfig { settings: &s, dirs: &dirs, daemon_exe: Some(Path::new("/usr/bin/goattyd")) });
        assert!(out.contains(r"_goatty_dir='/r o/ot'\''s/data/zsh'"), "{out}");
        assert!(out.contains("_goatty_user_rc='1'"));
        assert!(out.contains("_goatty_daemon='/usr/bin/goattyd'"));
        assert!(out.contains("_goatty_features=(autosuggestions syntax-highlighting atuin fzf integration)"));
        assert!(out.contains("_goatty_paths_syntax_highlighting=("));
        assert!(out.contains("/data/plugins/autosuggestions/zsh-autosuggestions.zsh'"));
    }

    #[test]
    fn write_only_rewrites_changes() {
        let tmp = tempfile::tempdir().unwrap();
        let dirs = Dirs::under(tmp.path());
        let s = ZshSettings::default();
        let files = render(&ZshConfig { settings: &s, dirs: &dirs, daemon_exe: None });
        assert!(write(&dirs, &files).unwrap());
        assert!(!write(&dirs, &files).unwrap());
        assert_eq!(std::fs::read_to_string(dirs.zsh_dir().join(".zshrc")).unwrap(), ZSHRC);
        let names: Vec<_> = std::fs::read_dir(dirs.zsh_dir()).unwrap().map(|e| e.unwrap().file_name()).collect();
        assert_eq!(names.len(), files.len(), "no temp files left: {names:?}");
    }
}
